export const SOCIAL_LINK_RE = /(facebook\.com\/groups|line\.me|discord\.gg|messenger\.com|t\.me\/)/i;

// เนื้อหาที่ "ใช่วยเรียนได้จริง" — ถ้าเจอคำเหล่านี้ให้เก็บไว้แม้จะเข้าข่ายข้างบน
// "คลิป/วิดีโอ" อยู่ตรงนี้เพราะคลิปบรรยายคือเนื้อหาจริง
// แม้ชื่อไฟล์จะมีคำว่า "เรียนออนไลน์" ก็ตาม (เช่น "คลิปที่เรียนออนไลน์-30-07-69")
export const STUDY_CONTENT_RE = /(สรุป|ทฤษฎี|แนวคิด|ตัวอย่าง|แบบฝึกหัด|แบบทดสอบ|สูตร|ทฤษฎีบท|นิยาม|คำสั่ง|วิธีทำ|ขั้นตอน|คลิป|วีดีโอ|วิดีโอ|chapter|lecture|slide|homework|assignment|ใบงาน|summar)/i;

// ข้อความคุยเล่น/ถามเล็กๆ ที่ไม่มีสาระ เช่น ทักอาจารย์ ขอบคุณ บ่นฝน
// ระวัง: ห้ามใส่คำกว้างๆ — นักศึกษาถามสั้นๆ ก็มีค่า เช่น "หา Euler path"
export const CHATTER_RE = /^(อาจารย์คะ|อาจารย์ครับ|ขอบคุณครับ|ขอบคุณค่ะ|ขอโทษครับ|โทษค่ะ|ขอโทษค่ะ|sorry|ok+|รับทราบ|ขอบคุณครับครับ)/i;

/** ประกาศล้วนๆ ที่ไม่มีไฟล์แนบ — เก็บเฉพาะที่ดูเป็นเนื้อหาการเรียนจริง */
export function isStudyContent(text: string) {
  const t = text.trim();
  if (STUDY_CONTENT_RE.test(t)) return true;
  if (CHATTER_RE.test(t)) return false;
  if (SCHEDULE_RE.test(t)) return false;
  if (SOCIAL_LINK_RE.test(t) && t.length < 400) return false;
  // สั้นมากจนไม่มีความหมาย (พิมพ์ผิด / อีโมจิลอย่างเดียว)
  // — ขีดล่างต่ำมาก เพราะ "หา Euler path" สั้นแต่มีค่ามาก
  return letterCount(t) >= 8;
}

