/**
 * นิสิตคุยกันเองในกลุ่ม ไม่ใช่เนื้อหา
 * ใช้ "ค้าบ / มั้ย / อ้ะ" เป็นสัญญาณ เพราะงานจริงไม่มีคำเหล่านี้
 * (ต่างจาก CHATTER_FIRST_RE ตัวนี้ไม่ override เอกสารใบงาน)
 */
export const CASUAL_CHATTER_RE = /(ค้าบ|มั้ย|มั๊ย|อิ๊ว|ยิ้มๆ|ขออยู้ด้วย|คนเดียว)/;

/**
 * เอกสารที่เป็น "ใบงาน/แบบฝึกหัด" จริง ๆ
 * ต้องชนะคำในชื่อเสมอ ไม่ว่าจะพูดถึง ลงชื่อ / ส่งงาน / ผลสะสม อย่างไร
 * เช่น "การลงชื่อสร้างทีมบริษัทสำนักงานดิจิทัล ใบงานที่ 5" = ใบงานจริง ไม่ใช่ฟอร์มเช็คชื่อ
 */
export const WORKSHEET_RE = /(ใบงาน|แบบฝึกหัด|มคอ|assignment|worksheet|lab\s*sheet|\blab\s*\d)/i;

/**
 * นิสิตขอส่งงาน/ขออนุญาต = แชทในกลุ่ม ไม่ใช่เอกสาร
 * แม้แต่ชื่อจะมีคำว่า "ใบงาน" ก็ยังต้องตัด
 * เช่น "อาจารย์ครับ ขออนุญาต ส่งงานใบงานที่1ครับ"
 */
export const CHATTER_FIRST_RE = /(ขออนุญาต|ขอส่งงาน|ครับทราบ|รับทราบครับ)/;

/** มีเนื้อหาจริงให้เรียนไหม (สไลด์รูปภาพที่ดึงข้อความไม่ได้ = ไม่มี) */
export function hasSubstantiveContent(m: { title?: string | null; fileName?: string | null; textContent?: string | null }): boolean {
  const name = String(m.title || "") + " " + String(m.fileName || "");
  // แชทนิสิต = ตัดเสมอ แม้ชื่อจะดูเหมือนใบงาน
  if (CHATTER_FIRST_RE.test(name)) return false;
  // ใบงาน/แบบฝึกหัด = เนื้อหาเสมอ ไม่ต้องเช็คชื่อธุระจัดการ
  if (!WORKSHEET_RE.test(name) && (ADMIN_NAME_RE.test(name) || CASUAL_CHATTER_RE.test(name))) return false;
  return contentQuality(m).hasText;
}

/**
 * ชุดอักขระที่ "นับเป็นตัวหนังสือ" ได้
 *
 * ข้อควรระวัง: สระและวรรณยุกต์ของภาษาไทย (ัิ ี ึ ื ุ ู ่ ้ ๊ ๋์) ไม่ได้อยู่ในกลุ่ม \p{L}
 * แต่อยู่ในกลุ่ม \p{M} (Mark) ถ้าเขียน regex เป็น [^\p{L}] มันจะไปตัดสระทิ้ง
 *
 * ผลที่เคยเจอ: หัวข้อ KnowledgeNode ออกมาเป็น "การบานเสนทางทสนทสดทำขอ"
 * (ต้นฉบับคือ "การวางเสนอทางที่สั้นที่สุดทำข้อ") เพราะ \p{L} ไม่นับสระ
 */
export const NON_TEXT_CHAR_RE = /[^\p{L}\p{N}\p{M}]/gu;
export const LETTER_CHAR_RE = /[\p{L}\p{M}]/u;
/** นับตัวอักษรแบบไทยถูกต้อง (นับสระด้วย) */
export function letterCount(text: string) {
  return String(text || "").replace(NON_TEXT_CHAR_RE, "").length;
}

/** ชื่อที่ไม่มีความหมาย — เกิดตอน Google Doc/Sheet ไม่มี title
 * แอปควรใช้ "ชื่อไฟล์จริง" แทน ไม่ใช่คำว่า "เอกสาร" หรือ "Material"
 */

export const GENERIC_TITLE_RE = /^(เอกสาร|เอกสาร\s*\d*|material|ไฟล์|สื่อจาก\s*google\s*classroom|untitled(\s+document)?|document|slide|presentation|แนว|แนวคำตอบ|ใบงาน|วัตถุ|object)\s*$/i;

/**
 * ชื่อที่ไม่มีเนื้อหา แม้ไม่ตรง GENERIC_TITLE_RE พอดี
 *
 * Google Classroom ตั้งชื่อ Doc/PPT ว่า "เอกสารประกอบการเรียน" ทั้งวิชาทั้ง 20 ไฟล์
 * แต่ชื่อไฟล์จริงคือ "บทที่ 7 การใช้งานดิจิทัลเพื่อการทำงาน" — อันหลังมีค่ามากกว่า
 * ต้องยอมรับทั้ง "เอกสารประกอบการเรียน" และ "Material-ประกอบการเรียน" และ "เอกสารประกอบ-16"
 */
export const GENERIC_STEM_RE = /^\s*((เอกสาร|material|ไฟล์|file|doc(ument)?|slide)((-ประกอบการเรียน|-ประกอบรายวิชา|-ประกอบ|ประกอบการเรียน|ประกอบรายวิชา|ประกอบ)?\s*[-–—:\s]?\s*[\d\s\-–—]*))\s*$/i;

export function isGenericTitle(title: string) {
  const t = String(title || "").trim();
  return GENERIC_TITLE_RE.test(t) || GENERIC_STEM_RE.test(t);
}

/** ชื่อไฟล์ที่ยังไม่มีความหมาย (ไม่ควรเอามาแทนชื่อที่ดีกว่า) */
function isWeakFileName(fileName: string) {
  const f = String(fileName || "").trim();
  if (!f) return true;
  if (isGenericTitle(f)) return true;
  // เลข/hash ล้วน เช่น 8bc647173a8bebfece49aa93.pdf
  return !LETTER_CHAR_RE.test(f.replace(/\.[a-z0-9]{2,5}$/i, ""));
}

/** ชื่อที่ควรแสดงผู้ใช้ */
export function displayTitle(title: string, fileName: string) {
  const t = String(title || "").trim();
  const f = String(fileName || "").trim();
  if (t && !isGenericTitle(t)) return t;
  if (f && !isWeakFileName(f)) return f.replace(/\.[a-z0-9]{2,5}$/i, "");
  return t || "ไม่มีชื่อ";
}

/**
 * ตัดข้อความสำเร็จรูปที่แอบติดมากับทุกไฟล์ออก
 * เหลือแต่ "เนื้อหาจริง" ของไฟล์นั้น
 * (เช่น "WEEK#14 Array-2 ส่ง code+ผลรัน N>=6" ยังเหลือ · "เอกสาร + ไฟล์แนบ + ลิงก์" เหลือแค่คำเดียว)
 */
const BOILERPLATE_RE = /(ไฟล์แนบ[^\n]*|เปิดไฟล์ต้นฉบับ[^\n]*|หากเปิดไม่ได้[^\n]*|ไฟล์ต้นฉบับ:[^\n]*|คลิปการสอน|แบบฟอร์ม:\s*[^\n]*|ลิงก์:\s*[^\n]*)/g;

export function meaningfulText(text: string | null | undefined) {
  return String(text || "")
    .replace(BOILERPLATE_RE, " ")
    .replace(/https?:\/\/\S+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * รูปภาพที่ไม่เหลือเนื้อหาให้ AI ใช้เลย (สกรีนช็อต/รูปถ่ายที่ไม่มีคำอธิบาย)
 * ระวัง: รูปที่แนบมากับงานมักมีคำอธิบายงานติดมาด้วย อย่าลบทิ้ง
 */
export function isUnusableImage(mimeType: string | null | undefined, textContent: string | null | undefined) {
  if (!String(mimeType || "").startsWith("image/")) return false;
  return meaningfulText(textContent).length < 12;
}

export function classifyExistingMaterial(m: { title?: string | null; fileName?: string | null; textContent?: string | null; externalId?: string | null; driveFileId?: string | null; mimeType?: string | null }) {
  const title = String(m.title || "");
  const fileName = String(m.fileName || "");
  const text = String(m.textContent || "");
  const externalId = String(m.externalId || "");

  // ไม่แตะของที่ผู้ใช้อัปโหลดเอง — ตัดสินใจเองได้ว่าจะเก็บอะไร
  if (!externalId) return "keep";

  // รูปภาพที่ไม่มีข้อความให้ AI ใช้
  if (isUnusableImage(m.mimeType, m.textContent)) return "junk-image";

  // ไฟล์นอกวิชา เช่น หนังสือเชิญฝึกทหาร
  if (isOffTopicFile(fileName) || isOffTopicFile(title)) return "junk-offtopic";

  // มีไฟล์จริงแนบมา = เนื้อหา (เช่น CPU.pdf, แนวข้อสอบ Mid.docx, สรุปข้อสอบปลายภาค.pdf)
  // ข้อความประกาศที่แนบมาด้วยมักเป็นแค่คำบรรยายของไฟล์ ไม่ใช่เนื้อหาแยก
  if (m.driveFileId || fileName) {
    if (LOGISTICS_FILE_RE.test(fileName)) return "junk-logistics-file";
    return "keep";
  }

  // ข้อความล้วน = ประกาศ ต้องเข้ม
  const body = [title, text].filter(Boolean).join("\n");
  if (isNoisePost(body)) return "junk-noise";
  if (!isStudyContent(body)) return "junk-notice";
  return "keep";
}