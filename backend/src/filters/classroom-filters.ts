/**
 * ประเมินคุณภาพเนื้อหาของไฟล์
 *
 * ตั้งใจแยกสองเรื่องนี้ออกจากกัน เพราะคนละเรื่อง:
 *
 * 1) "ตัดทิ้งเลย"   = สไลด์รูปภาพที่ดึงข้อความไม่ได้ (สัดส่วนตัวอักษรต่ำมาก)
 *    เช่น Chapter 7 Memory 137 ตัวอักษร ในไฟล์ 1,031 ไบต์ (13%)
 *    -> เนื้อหาจริงอยู่ในรูป ไม่มีทางใช้ และทำให้ผู้ใช้เห็นสไลด์ไม่ครบ
 *
 * 2) "เก็บไว้ แต่ใช้ทำโจทย์ไม่ได้" = สไลด์ที่มีข้อความจริงแต่สั้น
 *    เช่น "บทที่ 1 ตรรกศาตร์ Boolean Logic" (94 ตัวอักษร 77%)
 *    -> เป็นโครงเรียนของวิชา ต้องเก็บไว้เป็นหัวข้อ ถ้าตัดทิ้งวิชาจะไม่มีอะไรให้เรียน
 *
 * ตัวอย่างจริงจาก 1204101 (คณิตศาสตร์):
 *   Finite Automata        3,417 ตัว (51%) -> เก็บ + ใช้ทำโจทย์ได้
 *   บทที่ 1 ตรรกศาตร์ Boolean  94 ตัว (77%) -> เก็บเป็นหัวข้อ แต่ทำโจทย์ไม่ได้
 *   Chapter 2 องค์ประกอบ       67 ตัว (17%) -> ตัดทิ้ง เป็นสไลด์รูปภาพ
 */
export const MIN_LETTERS = 200;   // ต่ำกว่านี้ = ทำโจทย์ไม่ได้ แต่ยังเก็บเป็นหัวข้อได้
export const MIN_RATIO = 30;      // ต่ำกว่านี้ = สไลด์รูปภาพ ตัดทิ้งเลย

export function contentQuality(m: { textContent?: string | null }) {
  const raw = String(m.textContent || "");
  const letters = letterCount(raw);
  const ratio = raw.length ? Math.round((letters / raw.length) * 100) : 0;
  return {
    letters,
    ratio,
    /** มีข้อความจริงให้ใช้ — ไม่ใช่สไลด์รูปภาพ */
    hasText: ratio >= MIN_RATIO,
    /** เนื้อหาหนาแน่นพอจะตั้งเป็นโจทย์ได้ */
    enoughForQuiz: letters >= MIN_LETTERS && ratio >= MIN_RATIO,
  };
}

