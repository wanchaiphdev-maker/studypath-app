export const LEAVE_REQUEST_RE = /(ขออนุญาติ?ลา|ขอลาหยุด|ขอลา|อนุญาติ?ลา|ลาส่วม|ลาป่วย|ลาไข้|ลากิจ|ลาพักผ่อน|ลาฉุกเฉิน|ลาหยุด|ลาพักลา|ลาเรียน|ลาด้วย|ใบลา)/;

// โพสต์ขอสมัครเข้าเรียน / หาสมาชิกเข้ากลุ่ม (ไม่ใช่เนื้อหาการเรียน)
// ไม่ผูก ^ เพราะของจริงมักมีคำนำหน้า เช่น "ยังไม่มีกลุ่มครับหากลุ่ม" / "มีใครขาดไหมครับ"
export const GROUP_CHATTER_RE = /(หากลุ่ม|หาคนเข้ากลุ่ม|มีกลุ่มไหน|มีกลุ่มยังไม่มีกลุ่ม|มีใครยังไม่มีกลุ่ม|ยังไม่มีกลุ่ม|ยังไม่มีกลุ่มเลย|กลุ่มไหนขาด|กลุ่มใครขาด|ใครขาดไหม|คนขาดไหม|ขอไอจีเพื่อนกลุ่ม|ขออนุญาตค่ะมีกลุ่ม|อยู่ด้วยครับ|ขออยู่ด้วยครับ|เข้ามาในกลุ่มนี้|request เข้ามาในกลุ่ม)/;

// โพสต์ขอสมัครเข้าเรียน (นักศึกษาทักอาจารย์ในกลุ่มวิชา)
export const ENROLL_REQUEST_RE = /เรียน\s*(ท่าน|รองศาสตราจารย์|ผศ\.|อาจารย์)/;

// เนื้อหาสำคัญ ห้ามกรองทิ้งแม้จะเจอคำที่คล้ายกัน
// หมายเหตุ: ตัดคำว่า "ประกาศ" ออก — กว้างเกินจนปล่อยให้ "ประกาศ พรุ่งนี้สอบกลางภาค" หลุด
export const KEEP_CONTENT_RE = /(ใบงาน|แบบฝึกหัด|แบบทดสอบ|คลิปการสอน|การสอนออนไลน์|งานกลุ่ม-วินิจ|งานกลุ่ม\(คลิป\)|เอกสารประกอบ|สรุปเล่ม)/;

export function isNoisePost(text: string) {
  const t = text.trim();
  if (KEEP_CONTENT_RE.test(t)) return false;
  return LEAVE_REQUEST_RE.test(t) || ENROLL_REQUEST_RE.test(t) || GROUP_CHATTER_RE.test(t);
}

